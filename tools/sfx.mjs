// Collect every sound effect the sections declare (src/scenes/*: <section>Sfx(env)) into data/sfx.json.
// Then: .venv/Scripts/python tools/make_sfx.py  (synthesises them and mixes them under the music).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Features } from '../src/engine/features.js';
import { Lyrics } from '../src/engine/lyrics.js';
import { buildSfx } from '../src/scenes/index.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'config.json'), 'utf8'));
const features = new Features(JSON.parse(fs.readFileSync(path.join(ROOT, cfg.paths.features), 'utf8')), cfg);
const lyrics = new Lyrics(JSON.parse(fs.readFileSync(path.join(ROOT, cfg.paths.lyrics), 'utf8')), cfg, features);
const ev = await buildSfx({ cfg, features, lyrics, art: null });
fs.writeFileSync(path.join(ROOT, 'data/sfx.json'), JSON.stringify({ _doc: 'generated by tools/sfx.mjs from the section files; do not edit', events: ev }, null, 1));
console.log(`[sfx] ${ev.length} events -> data/sfx.json`);
